"""Write audited experiment values as reusable LaTeX commands."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def command(name: str, value) -> str:
    return rf"\providecommand{{\{name}}}{{{value}}}"


def format_p(value: float) -> str:
    value = float(value)
    if value < 1e-4:
        mantissa, exponent = f"{value:.2e}".split("e")
        return rf"{mantissa}\times10^{{{int(exponent)}}}"
    return f"{value:.6f}"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("paper/ieee_superquadric/results_auto.tex"),
    )
    parser.add_argument(
        "--sq-robust-summary",
        type=Path,
        default=Path(
            r"C:\code\Fiting\outputs\optimizer_comparison\v3_stratified9_robustness_guided_pso_5seeds_20260721\summary\summary.json"
        ),
    )
    args = parser.parse_args()
    outputs = Path(r"C:\code\Fiting\outputs")
    main_pmf = load(outputs / "pmf_cylinder_comparison/pso_cs_formal20_20260722/audit.json")
    support = load(outputs / "pmf_cylinder_density_support/formal_adaptive_20260721/ablation_summary.json")
    area = load(outputs / "area_weight_ablation/formal_v2_pso_clean_48x48_5008fe_5seeds/audit.json")
    guided = load(outputs / "optimizer_comparison/guided_initialization_ablation_summary/audit.json")
    sq_clean = load(
        outputs
        / "optimizer_comparison/v3_stratified9_clean_guided_pso_1seed_20260716/summary_5seeds/summary.json"
    )
    sq_robust_path = args.sq_robust_summary.resolve()
    if not sq_robust_path.exists():
        sq_robust_path = (
            outputs / "optimizer_comparison/v3_stratified9_robustness_summary/summary.json"
        )
    sq_robust = load(sq_robust_path)
    budget_path = (
        outputs
        / "pmf_cylinder_budget_sensitivity/preregistered_20260721/summary.json"
    )
    budget_summary = load(budget_path) if budget_path.exists() else None
    occlusion_feasibility = load(
        outputs / "environment/occlusion_search_feasibility_audit.json"
    )
    if occlusion_feasibility.get("status") != "PASS":
        raise ValueError("occlusion search-feasibility audit did not pass")

    clean = main_pmf["paired_summary"]["clean"]
    out50 = main_pmf["paired_summary"]["outlier_50"]
    lines = [
        "% Generated by tools/write_paper_result_macros.py; do not edit values manually.",
        command("PMFCleanPSOMedian", f'{clean["pso_chamfer"]["median"]:.5f}'),
        command("PMFCleanCSMedian", f'{clean["cs_chamfer"]["median"]:.5f}'),
        command("PMFCleanPSOSuccess", f'{clean["pso_successes"]}/20'),
        command("PMFCleanCSSuccess", f'{clean["cs_successes"]}/20'),
        command("PMFCleanPSOWins", f'{clean["pso_wins"]}/20'),
        command("PMFCleanWilcoxonP", f'{clean["wilcoxon_exact_two_sided_p"]:.6f}'),
        command("PMFOutlierFiftyPSOMedian", f'{out50["pso_chamfer"]["median"]:.5f}'),
        command("PMFOutlierFiftyCSMedian", f'{out50["cs_chamfer"]["median"]:.5f}'),
        command("PMFOutlierFiftyPSOSuccess", f'{out50["pso_successes"]}/20'),
        command("PMFOutlierFiftyCSSuccess", f'{out50["cs_successes"]}/20'),
        command("PMFOutlierFiftyWilcoxonP", f'{out50["wilcoxon_exact_two_sided_p"]:.3f}'),
        command(
            "SQOcclusionCenterFeasible",
            f'{occlusion_feasibility["center_feasible_cases"]}/{occlusion_feasibility["cases"]}',
        ),
        command(
            "SQOcclusionCenterInfeasible",
            f'{occlusion_feasibility["center_infeasible_cases"]}/{occlusion_feasibility["cases"]}',
        ),
    ]
    for condition, prefix in (("clean", "SupportClean"), ("outlier_50", "SupportOutlierFifty"), ("outlier_80", "SupportOutlierEighty")):
        cell = support["conditions"].get(condition, {})
        if not cell.get("paired_seeds"):
            continue
        full = cell["variants"]["full_input"]
        adaptive = cell["variants"]["adaptive_density"]
        lines.extend(
            [
                command(prefix + "FullMedian", f'{full["paired_chamfer"]["median"]:.5f}'),
                command(prefix + "AdaptiveMedian", f'{adaptive["paired_chamfer"]["median"]:.5f}'),
                command(prefix + "FullSuccess", f'{full["paired_successes"]}/5'),
                command(prefix + "AdaptiveSuccess", f'{adaptive["paired_successes"]}/5'),
                command(prefix + "WilcoxonP", f'{cell["paired_comparison"].get("wilcoxon_exact_two_sided_p", float("nan")):.3f}'),
            ]
        )
    for shape, prefix in (("box", "AreaBox"), ("ellipsoid", "AreaEllipsoid"), ("cylinder", "AreaCylinder")):
        cell = area["shapes"][shape]
        lines.extend(
            [
                command(prefix + "UniformMedian", f'{cell["uniform_chamfer"]["median"]:.5f}'),
                command(prefix + "WeightedMedian", f'{cell["area_weighted_chamfer"]["median"]:.5f}'),
                command(prefix + "UniformSuccess", f'{cell["uniform_successes"]}/5'),
                command(prefix + "WeightedSuccess", f'{cell["area_weighted_successes"]}/5'),
            ]
        )
    for shape, prefix in (("box", "InitBox"), ("cylinder", "InitCylinder"), ("ellipsoid", "InitEllipsoid")):
        cell = guided["shapes"][shape]
        lines.extend(
            [
                command(prefix + "RandomMedian", f'{cell["random_chamfer"]["median"]:.5f}'),
                command(prefix + "GuidedMedian", f'{cell["guided_chamfer"]["median"]:.5f}'),
                command(prefix + "RandomSuccess", f'{cell["random_successes"]}/5'),
                command(prefix + "GuidedSuccess", f'{cell["guided_successes"]}/5'),
            ]
        )
    robust_clean = sq_robust.get("conditions", {}).get("clean")
    if robust_clean and robust_clean["guided_pso_runs"]["runs"]:
        clean_pso = robust_clean["guided_pso_runs"]
        clean_ems = robust_clean["ems_cases"]
        clean_comparison = robust_clean["pso_median_vs_ems"]
        independent_cases = len(clean_comparison["paired_cases"])
        lines.extend(
            [
                command("SQIndependentCases", independent_cases),
                command("SQRunsPerCondition", clean_pso["runs"]),
                command("SQRandomPSOMedian", f'{clean_pso["chamfer"]["median"]:.5f}'),
                command("SQRandomPSOSuccess", f'{clean_pso["successes"]}/{clean_pso["runs"]}'),
                command("SQRandomEMSMedian", f'{clean_ems["chamfer"]["median"]:.5f}'),
                command("SQRandomEMSSuccess", f'{clean_ems["successes"]}/{clean_ems["cases"]}'),
                command("SQRandomEMSWins", f'{clean_comparison["ems_wins"]}/{independent_cases}'),
                command(
                    "SQRandomWilcoxonP",
                    format_p(clean_comparison["wilcoxon"]["exact_two_sided_p"]),
                ),
            ]
        )
    else:
        lines.extend(
            [
                command("SQIndependentCases", 9),
                command("SQRunsPerCondition", 45),
                command("SQRandomPSOMedian", f'{sq_clean["pso_all_runs"]["chamfer"]["median"]:.5f}'),
                command("SQRandomPSOSuccess", f'{sq_clean["pso_all_runs"]["success_count"]}/45'),
                command("SQRandomEMSMedian", f'{sq_clean["ems_cases"]["chamfer"]["median"]:.5f}'),
                command("SQRandomEMSSuccess", f'{sq_clean["ems_cases"]["success_count"]}/9'),
                command("SQRandomEMSWins", f'{sq_clean["paired_comparison"]["ems_wins"]}/9'),
                command("SQRandomWilcoxonP", f'{sq_clean["paired_comparison"]["wilcoxon_exact_two_sided_p"]:.6f}'),
            ]
        )
    ems_occ = sq_robust["conditions"]["occlusion_cap_80"]["ems_cases"]
    lines.extend(
        [
            command("EMSOcclusionMedian", f'{ems_occ["chamfer"]["median"]:.5f}'),
            command("EMSOcclusionSuccess", f'{ems_occ["successes"]}/{ems_occ["cases"]}'),
            command("EMSOcclusionRuntime", f'{ems_occ["runtime_s"]["median"]:.3f}'),
        ]
    )
    robust_conditions = (
        ("noise_1pct_diag", "SQNoise"),
        ("outlier_20", "SQOutlier"),
        ("missing_80", "SQRandomMissing"),
        ("occlusion_cap_80", "SQOcclusion"),
    )
    for condition, prefix in robust_conditions:
        cell = sq_robust["conditions"][condition]
        pso = cell["guided_pso_runs"]
        ems = cell["ems_cases"]
        if int(pso["runs"]) <= 0:
            continue
        lines.extend(
            [
                command(prefix + "PSOMedian", f'{pso["chamfer"]["median"]:.5f}'),
                command(prefix + "PSOSuccess", f'{pso["successes"]}/{pso["runs"]}'),
                command(
                    prefix + "PSOSuccessAtSix",
                    f'{pso["success_threshold_sensitivity"]["0.060"]}/{pso["runs"]}',
                ),
                command(prefix + "EMSMedian", f'{ems["chamfer"]["median"]:.5f}'),
                command(prefix + "EMSSuccess", f'{ems["successes"]}/{ems["cases"]}'),
                command(
                    prefix + "RelativeDegradation",
                    f'{cell["paired_to_clean"]["relative_degradation"]["median"]:.3f}',
                ),
            ]
        )
        for stratum, stratum_prefix in (
            ("smooth", "Smooth"),
            ("mixed", "Mixed"),
            ("boxy", "Boxy"),
        ):
            stratum_runs = cell["strata"]["shape"][stratum]["guided_pso_runs"]
            lines.append(
                command(
                    prefix + stratum_prefix + "Success",
                    f'{stratum_runs["successes"]}/{stratum_runs["runs"]}',
                )
            )
        paired_clean_test = cell["paired_to_clean"].get("wilcoxon")
        if paired_clean_test is not None:
            lines.append(
                command(
                    prefix + "PairedCleanP",
                    format_p(paired_clean_test["exact_two_sided_p"]),
                )
            )
        comparison_test = cell["pso_median_vs_ems"].get("wilcoxon")
        if comparison_test is not None:
            lines.append(
                command(
                    prefix + "PSOvsEMSP",
                    format_p(comparison_test["exact_two_sided_p"]),
                )
            )
    if budget_summary is not None and budget_summary.get("status") == "PASS":
        budget_names = (
            ("50000", "BudgetFiftyK"),
            ("199920", "BudgetTwoHundredK"),
            ("499920", "BudgetFiveHundredK"),
        )
        condition_names = (("clean", "Clean"), ("outlier_50", "OutlierFifty"))
        if all(value in budget_summary.get("budgets", {}) for value, _ in budget_names):
            for budget, budget_prefix in budget_names:
                for condition, condition_prefix in condition_names:
                    cell = budget_summary["budgets"][budget]["conditions"][condition]
                    prefix = budget_prefix + condition_prefix
                    lines.extend(
                        [
                            command(prefix + "PSOMedian", f'{cell["pso_chamfer"]["median"]:.5f}'),
                            command(prefix + "CSMedian", f'{cell["cs_chamfer"]["median"]:.5f}'),
                            command(prefix + "PSOSuccess", f'{cell["pso_successes"]}/5'),
                            command(prefix + "CSSuccess", f'{cell["cs_successes"]}/5'),
                        ]
                    )
                    pvalue = cell.get("wilcoxon_exact_two_sided_p")
                    if pvalue is not None:
                        lines.append(command(prefix + "PSOvsCSP", f"{pvalue:.3f}"))
            for condition, condition_prefix in condition_names:
                for algorithm, algorithm_prefix in (("pso", "PSO"), ("cs", "CS")):
                    endpoint = budget_summary["within_algorithm"][condition][algorithm][
                        "50000_to_499920"
                    ]
                    test = endpoint.get("wilcoxon")
                    lines.append(
                        command(
                            "Budget" + condition_prefix + algorithm_prefix + "EndpointP",
                            "n/a" if test is None else f'{test["exact_two_sided_p"]:.3f}',
                        )
                    )
    output = args.output.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(lines) - 1} LaTeX result commands to {output}")


if __name__ == "__main__":
    main()
